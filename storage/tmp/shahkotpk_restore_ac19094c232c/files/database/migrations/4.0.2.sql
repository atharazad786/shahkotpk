-- ShahkotPK v4.0.2 Audit Logs & IP Location History
-- Coarse IP geolocation only. No silent GPS/device precise-location collection.

CREATE TABLE IF NOT EXISTS activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NULL,
 event_name VARCHAR(100) NOT NULL,
 event_category VARCHAR(60) NOT NULL DEFAULT 'activity',
 source VARCHAR(40) NOT NULL DEFAULT 'web',
 module VARCHAR(80) NULL,
 route VARCHAR(500) NULL,
 method VARCHAR(12) NULL,
 status_code INT NOT NULL DEFAULT 200,
 entity_type VARCHAR(100) NULL,
 entity_id BIGINT UNSIGNED NULL,
 ip_address VARCHAR(64) NULL,
 ip_hash CHAR(64) NULL,
 country_code VARCHAR(8) NULL,
 country VARCHAR(120) NULL,
 region_name VARCHAR(160) NULL,
 city VARCHAR(160) NULL,
 timezone_name VARCHAR(120) NULL,
 isp VARCHAR(190) NULL,
 asn VARCHAR(80) NULL,
 device_type VARCHAR(40) NULL,
 browser_name VARCHAR(80) NULL,
 os_name VARCHAR(80) NULL,
 user_agent VARCHAR(500) NULL,
 referrer VARCHAR(500) NULL,
 duration_ms INT NULL,
 meta_text MEDIUMTEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_activity_user (user_id,created_at),
 INDEX idx_activity_event (event_name,created_at),
 INDEX idx_activity_ip (ip_hash,created_at),
 INDEX idx_activity_location (country_code,city,created_at),
 INDEX idx_activity_route (module,created_at),
 CONSTRAINT fk_activity_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS user_location_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 location_fingerprint CHAR(64) NOT NULL,
 ip_hash CHAR(64) NOT NULL,
 ip_address VARCHAR(64) NULL,
 country_code VARCHAR(8) NULL,
 country VARCHAR(120) NULL,
 region_name VARCHAR(160) NULL,
 city VARCHAR(160) NULL,
 timezone_name VARCHAR(120) NULL,
 isp VARCHAR(190) NULL,
 asn VARCHAR(80) NULL,
 device_type VARCHAR(40) NULL,
 browser_name VARCHAR(80) NULL,
 os_name VARCHAR(80) NULL,
 source VARCHAR(40) NOT NULL DEFAULT 'web',
 first_seen_at DATETIME NOT NULL,
 last_seen_at DATETIME NOT NULL,
 visit_count BIGINT UNSIGNED NOT NULL DEFAULT 1,
 UNIQUE KEY uq_user_location (user_id,location_fingerprint),
 INDEX idx_location_user (user_id,last_seen_at),
 INDEX idx_location_ip (ip_hash,last_seen_at),
 INDEX idx_location_geo (country_code,city,last_seen_at),
 CONSTRAINT fk_location_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ip_geolocation_cache (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 ip_hash CHAR(64) NOT NULL UNIQUE,
 ip_address VARCHAR(64) NULL,
 provider VARCHAR(40) NOT NULL DEFAULT 'ipwhois',
 country_code VARCHAR(8) NULL,
 country VARCHAR(120) NULL,
 region_name VARCHAR(160) NULL,
 city VARCHAR(160) NULL,
 timezone_name VARCHAR(120) NULL,
 isp VARCHAR(190) NULL,
 asn VARCHAR(80) NULL,
 looked_up_at DATETIME NOT NULL,
 expires_at DATETIME NOT NULL,
 INDEX idx_geo_expiry (expires_at),
 INDEX idx_geo_city (country_code,city)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

